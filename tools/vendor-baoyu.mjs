#!/usr/bin/env node
// Usage: snapshot <srcDir> | snapshot --clone | snapshot --local key=path | apply-rewrites | --check
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const SOURCES = { repo: 'https://github.com/JimLiu/baoyu-design.git', ref: 'main', dir: 'vendor/baoyu-design' };
const SKIP = /^(docs|tests|test|screenshots|\.github)\//;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEST = path.join(ROOT, SOURCES.dir);
const MANIFEST = path.join(ROOT, 'vendor/manifest.json');
const REWRITES = path.join(ROOT, 'vendor-rewrites.json');
const NOTE = 'generated by tools/vendor-baoyu.mjs; do not edit';

function rewriteChanges(directory = DEST) {
  const entries = JSON.parse(fs.readFileSync(REWRITES, 'utf8'));
  if (!Array.isArray(entries)) throw new Error('Invalid rewrites: expected an array');
  const seen = new Set();
  const base = fs.realpathSync(directory);
  return entries.map((entry) => {
    if (!entry || typeof entry.file !== 'string' ||
        !/^skills\/[^/\\]+\/SKILL\.md$/.test(entry.file) ||
        entry.file.split('/').some((part) => part === '..' || part === '.') ||
        typeof entry.marker !== 'string' || !/^<!--[^\r\n]+-->$/.test(entry.marker) ||
        typeof entry.text !== 'string' || !entry.text.trim() || entry.text.includes(entry.marker) ||
        seen.has(entry.file)) {
      throw new Error('Invalid rewrite: expected unique skills/<id>/SKILL.md, marker and text');
    }
    seen.add(entry.file);
    const target = path.join(directory, entry.file);
    if (!fs.realpathSync(target).startsWith(`${base}${path.sep}`) || !fs.statSync(target).isFile()) {
      throw new Error(`Rewrite target escapes vendor or is not a file: ${entry.file}`);
    }
    const original = fs.readFileSync(target, 'utf8');
    const start = original.indexOf(entry.marker);
    // The marker owns the footer through EOF; upstream content stays before it.
    const prefix = start < 0 ? original : original.slice(0, start);
    const rewritten = `${prefix.trimEnd()}\n\n${entry.marker}\n${entry.text.trim()}\n`;
    return { file: entry.file, target, original, rewritten };
  });
}

function applyRewrites(directory = DEST) {
  // Validate every target before writing, including on staged snapshots.
  const changes = rewriteChanges(directory);
  const changed = changes.filter((entry) => entry.original !== entry.rewritten);
  for (const entry of changed) fs.writeFileSync(entry.target, entry.rewritten);
  return { ok: true, action: 'apply-rewrites', files: changes.length, changed: changed.map((entry) => entry.file) };
}

function git(src, args) {
  return execFileSync('git', ['-C', src, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

function writeManifest(value) {
  const temporary = `${MANIFEST}.${process.pid}.tmp`;
  try {
    fs.writeFileSync(temporary, `${JSON.stringify(value, null, 2)}\n`, { flag: 'wx' });
    fs.renameSync(temporary, MANIFEST);
  } finally {
    fs.rmSync(temporary, { force: true });
  }
}

function manifest(commit, files) {
  return { generatedAt: new Date().toISOString(), source: { repo: SOURCES.repo, ref: SOURCES.ref, commit }, files, note: NOTE };
}

function countFiles(dir) {
  let count = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) count += countFiles(path.join(dir, entry.name));
    else if (entry.isFile() || entry.isSymbolicLink()) count++;
    else throw new Error(`Unsupported file type: ${path.join(dir, entry.name)}`);
  }
  return count;
}

function check() {
  const actual = countFiles(DEST);
  const rewriteDrift = rewriteChanges().filter((entry) => entry.original !== entry.rewritten).map((entry) => entry.file);
  if (!fs.existsSync(MANIFEST)) {
    writeManifest(manifest('unknown', actual));
    return { ok: rewriteDrift.length === 0, action: 'baseline-created', directory: SOURCES.dir, expected: actual, actual, commit: 'unknown', rewriteDrift };
  }
  const value = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  if (!Number.isSafeInteger(value.files) || value.files < 0 ||
      value.source?.repo !== SOURCES.repo || value.source?.ref !== SOURCES.ref ||
      typeof value.source?.commit !== 'string' || !value.source.commit) {
    throw new Error('Invalid manifest: expected nonnegative files and matching source repo/ref/commit');
  }
  return { ok: actual === value.files && rewriteDrift.length === 0, action: 'check', directory: SOURCES.dir, expected: value.files, actual, delta: actual - value.files, commit: value.source.commit, rewriteDrift };
}

function snapshot(source) {
  const src = fs.realpathSync(source);
  // A subdirectory's ls-files is relative to that directory; require the repository root.
  if (fs.realpathSync(git(src, ['rev-parse', '--show-toplevel']).trim()) !== src) {
    throw new Error('Source must be the root of a cloned Git repository');
  }
  if (src === DEST || DEST.startsWith(`${src}${path.sep}`) || src.startsWith(`${DEST}${path.sep}`)) {
    throw new Error('Source and destination must not contain one another');
  }
  const commit = git(src, ['rev-parse', 'HEAD']).trim();
  const files = git(src, ['ls-files', '-z']).split('\0').filter(Boolean).filter((name) => !SKIP.test(name));
  fs.mkdirSync(path.dirname(DEST), { recursive: true });
  const staging = fs.mkdtempSync(path.join(path.dirname(DEST), '.baoyu-snapshot-'));
  const staged = path.join(staging, 'new');
  const backup = path.join(staging, 'old');
  fs.mkdirSync(staged);
  let installed = false;
  let backedUp = false;
  try {
    for (const name of files) {
      if (path.isAbsolute(name) || name.split('/').some((part) => part === '..' || part === '.git')) {
        throw new Error(`Unsafe tracked path: ${name}`);
      }
      const from = path.join(src, name);
      const to = path.join(staged, name);
      fs.mkdirSync(path.dirname(to), { recursive: true });
      const stat = fs.lstatSync(from);
      if (stat.isSymbolicLink()) {
        const link = fs.readlinkSync(from);
        const resolved = path.resolve(path.dirname(to), link);
        if (path.isAbsolute(link) || !resolved.startsWith(`${staged}${path.sep}`)) {
          throw new Error(`Tracked symlink escapes snapshot: ${name}`);
        }
        fs.symlinkSync(link, to);
      } else if (stat.isFile()) {
        fs.copyFileSync(from, to);
        fs.chmodSync(to, stat.mode & 0o777);
      } else {
        throw new Error(`Tracked path is not a file (submodules are unsupported): ${name}`);
      }
    }
    if (countFiles(staged) !== files.length) throw new Error('Staged file count mismatch');
    applyRewrites(staged);
    if (fs.existsSync(DEST)) {
      fs.renameSync(DEST, backup);
      backedUp = true;
    }
    fs.renameSync(staged, DEST);
    installed = true;
    writeManifest(manifest(commit, files.length));
    return { ok: true, action: 'snapshot', directory: SOURCES.dir, files: files.length, source: { ...SOURCES, commit } };
  } catch (error) {
    if (installed) fs.rmSync(DEST, { recursive: true, force: true });
    if (backedUp) fs.renameSync(backup, DEST);
    throw error;
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
}

function main(args) {
  if (args.length === 1 && args[0] === '--check') return check();
  if (args.length === 1 && args[0] === 'apply-rewrites') return applyRewrites();
  if (args[0] === 'snapshot') args = args.slice(1);
  let src;
  let clone = false;
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--clone') {
      if (clone) throw new Error('Duplicate --clone');
      clone = true;
    } else if (arg === '--local') {
      const binding = args[++i] || '';
      const separator = binding.indexOf('=');
      if (separator <= 0 || separator === binding.length - 1 || src) throw new Error('Expected one --local key=path');
      // One configured source: the local key labels this source override.
      src = binding.slice(separator + 1);
    } else if (arg.startsWith('-') || src) {
      throw new Error(`Unexpected argument: ${arg}`);
    } else src = arg;
  }
  if (clone && src) throw new Error('--clone cannot be combined with a local source');
  if (!clone && !src) throw new Error('Usage: snapshot <srcDir> | snapshot --clone | --local key=path | apply-rewrites | --check');
  if (!clone) return snapshot(path.resolve(src));
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'vendor-baoyu-'));
  try {
    const checkout = path.join(temporary, 'source');
    execFileSync('git', ['clone', '--depth', '1', '--branch', SOURCES.ref, SOURCES.repo, checkout], { stdio: ['ignore', 'ignore', 'pipe'] });
    return snapshot(checkout);
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}

try {
  const report = main(process.argv.slice(2));
  console.log(JSON.stringify(report, null, 2));
  process.exitCode = report.ok ? 0 : 1;
} catch (error) {
  console.error(JSON.stringify({ ok: false, action: 'error', error: error.message }, null, 2));
  process.exitCode = 1;
}
